package mail

const (
	// FooterMarker 是通知页脚的第一行（标记行），渲染器把它原样写成页脚的第一行。解析器据它认出引用中的我方通知：
	// 没有引用头的 > 引用块只有在去掉前缀后含这一行（或 [TC）时才当作引用我方通知；剥离引用之后的新正文中仍有它，
	// 说明引用没有剥净。它只由可打印 ASCII 组成，不含 [TC 与令牌形状的串，正常文字里不会出现；解析器比较时忽略全部空白，
	// 被客户端折行或改动空白的副本同样认得出。
	FooterMarker = "---- TurnCourier ----"
	// FooterNotice 是页脚回复说明开头的固定句子。渲染器在页脚中写出「FooterNotice；请保留主题中的 [TC …] 标签，不要改动。」；
	// 解析器在新正文中发现它（忽略全部空白）即判定引用没有剥净。常量刻意不含后半句：后半句带着 [TC，那由 [TC 的残留检查负责，
	// 两条检查因此互不依赖，各自都能单独拦下残留。
	FooterNotice = "直接回复本邮件即可把新消息交给该任务"
	// IDHeader 是每封通知携带的自定义头，取值等于通知的我方 Message-ID（不含 nid、任务 ID 与令牌）。「已发送」副本的
	// Message-ID 被 QQ 改写，按这个头对应回通知（D4：定位副本只能按我方 ID 或我方自定义头，禁止按主题检索）。
	IDHeader = "X-TurnCourier-ID"
)
