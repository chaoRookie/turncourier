// TestCheckRejectsSymlinkedGoFiles 验证符号链接形式的 Go 源码直接报错，其他符号链接不被跟随，
// go 工具忽略的「.」「_」开头文件（如悬空的编辑器锁文件）不报错。
func TestCheckRejectsSymlinkedGoFiles(t *testing.T) {
	root := t.TempDir()
	outside := t.TempDir()
	source := writeFixture(t, outside, "bad.go", "package sample\nfunc Missing() {}\n")
	if err := os.Symlink(outside, filepath.Join(root, "linked")); err != nil {
		t.Skipf("当前平台不能创建符号链接: %v", err)
	}
	writeFixture(t, root, "doc.go", "// Package sample 中文说明。\npackage sample\n")
	for _, name := range []string{".#doc.go", "_backup.go"} {
		if err := os.Symlink(filepath.Join(root, "missing-target"), filepath.Join(root, name)); err != nil {
			t.Fatal(err)
		}
	}
	diagnostics, files, err := check(root)
	if err != nil || len(diagnostics) != 0 || files != 1 {
		t.Fatalf("check = %#v, %d, %v", diagnostics, files, err)
	}
	if err := os.Symlink(source, filepath.Join(root, "linked.go")); err != nil {
		t.Fatal(err)
	}
	if _, _, err := check(root); err == nil || !strings.Contains(err.Error(), "符号链接") {
		t.Fatalf("check error = %v，期望拒绝符号链接形式的 Go 源码", err)
	}
}

// TestRun 验证检查器退出码以及供人阅读的输出。
func TestRun(t *testing.T) {
	good := t.TempDir()
	writeFixture(t, good, "doc.go", "// Package good 中文说明。\npackage good\n")
	bad := t.TempDir()
	writeFixture(t, bad, "bad.go", "package bad\nfunc Missing() {}\n")
	empty := t.TempDir()
	cases := []struct {
		name string
		args []string
		code int
		text string
	}{
		{"pass", []string{good}, 0, "通过"},
		{"missing comments", []string{bad}, 1, "Missing"},
		{"missing root", []string{good + "/missing"}, 1, "commentcheck:"},
		{"empty root", []string{empty}, 1, "未找到手写 Go 文件"},
		{"extra args", []string{good, bad}, 2, "用法"},
		{"bad flag", []string{"-unknown"}, 2, "flag provided"},
		{"help", []string{"-h"}, 0, "用法"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			var stdout, stderr bytes.Buffer
			if code := run(tc.args, &stdout, &stderr); code != tc.code {
				t.Errorf("退出码 = %d，期望 %d", code, tc.code)
			}
			if !strings.Contains(stdout.String()+stderr.String(), tc.text) {
				t.Errorf("输出缺少 %q: %s%s", tc.text, &stdout, &stderr)
			}
		})
	}
}

// TestRunRejectsSymlinkRoot 验证符号链接根路径不会以零个文件静默通过。
func TestRunRejectsSymlinkRoot(t *testing.T) {
	target := t.TempDir()
	writeFixture(t, target, "bad.go", "package bad\nfunc Missing() {}\n")
	link := filepath.Join(t.TempDir(), "link")
	if err := os.Symlink(target, link); err != nil {
		t.Skipf("当前平台不能创建符号链接: %v", err)
	}
	var stdout, stderr bytes.Buffer
	if code := run([]string{link}, &stdout, &stderr); code != 1 || !strings.Contains(stderr.String(), "未找到手写 Go 文件") {
		t.Fatalf("退出码 = %d，输出: %s%s", code, &stdout, &stderr)
	}
}

