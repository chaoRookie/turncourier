// TestCheckReportsMissingChinese 验证英文或无汉字注释、缺失注释、方法、局部类型以及多项声明逐项报错。
func TestCheckReportsMissingChinese(t *testing.T) {
	root := t.TempDir()
	writeFixture(t, root, "bad.go", `// Package sample is undocumented in Chinese.
package sample
// Worker processes jobs.
type Worker struct{}
type Runner interface { Run() }
// 此分组说明不能代替各类型的说明。
type ( First int; Second string )
// Run processes a job.
func Run() {}
func hidden() {}
func (Worker) Stop() {}
// Loop — runs forever…
func Loop() {}
// Build 构建局部状态。
func Build() { type localState struct{ n int }; _ = localState{} }
`)
	writeFixture(t, root, "bad_test.go", "package sample\nfunc TestMissing() {}\n")
	want := []string{
		"包 sample 缺少中文包级文档",
		"类型 Worker 缺少中文文档注释",
		"类型 Runner 缺少中文文档注释",
		"类型 First 缺少中文文档注释",
		"类型 Second 缺少中文文档注释",
		"函数 Run 缺少中文文档注释",
		"函数 hidden 缺少中文文档注释",
		"函数 Stop 缺少中文文档注释",
		"函数 Loop 缺少中文文档注释",
		"类型 localState 缺少中文文档注释",
		"函数 TestMissing 缺少中文文档注释",
	}
	diagnostics, files, err := check(root)
	if err != nil || files != 2 || len(diagnostics) != len(want) {
		t.Fatalf("check = %#v, %d, %v", diagnostics, files, err)
	}
	for i, item := range diagnostics {
		if item.Position.Line <= 0 || item.Message != want[i] {
			t.Fatalf("诊断 %d = %#v，期望 %q", i, item, want[i])
		}
	}
}

// TestCheckGeneratedAndExcluded 验证标准生成文件和 go 工具忽略的目录豁免，但非标准生成标记和正常测试源码不会豁免。
func TestCheckGeneratedAndExcluded(t *testing.T) {
	root := t.TempDir()
	for _, directory := range []string{".git", ".local", ".cache", ".hg", ".svn", ".claude/worktrees/x", "_old", "vendor", "testdata"} {
		writeFixture(t, root, directory+"/bad.go", "invalid syntax")
	}
	writeFixture(t, root, "generated.go", "// Code generated by test. DO NOT EDIT.\npackage sample\nfunc Generated() {}\n")
	writeFixture(t, root, "fake.go", "package sample\n// Helper wraps things. DO NOT EDIT.\nfunc Helper() {}\n")
	writeFixture(t, root, "handwritten.go", "// Code generated by hand.\npackage sample\nfunc Handwritten() {}\n")
	writeFixture(t, root, "plain.txt", "not Go")
	writeFixture(t, root, "real.go", "// Package sample 中文说明。\npackage sample\n")
	writeFixture(t, root, "real_test.go", "package sample\nfunc TestMissing() {}\n")
	want := []string{"Helper", "Handwritten", "TestMissing"}
	diagnostics, files, err := check(root)
	if err != nil || files != 4 || len(diagnostics) != len(want) {
		t.Fatalf("check = %#v, %d, %v", diagnostics, files, err)
	}
	for i, name := range want {
		if !strings.Contains(diagnostics[i].Message, name) {
			t.Fatalf("诊断 %d = %#v，期望包含 %q", i, diagnostics[i], name)
		}
	}
}

